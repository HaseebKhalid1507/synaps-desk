#!/usr/bin/env python3
"""Regenerate crates/synaps-desktop/src/palettes.rs: the Synaps TUI's 20 static
palettes (agent-tui/src/tui/theme), copied as data. They are private to
agent-tui, so the desktop keeps a copy; this script is how it stays in step.

usage: scripts/gen-palettes.py [AGENT_RUNTIME_REPO] [REF]       (writes the file)
       scripts/gen-palettes.py --check [AGENT_RUNTIME_REPO] [REF] (exit 1 if it differs)
Defaults: ~/Projects/agent-runtime, origin/dev. `myx` (album-reactive) is left out.
"""
import os
import re
import subprocess
import sys

check = "--check" in sys.argv
args = [a for a in sys.argv[1:] if a != "--check"]
repo = os.path.expanduser(args[0] if args else "~/Projects/agent-runtime")
ref = args[1] if len(args) > 1 else "origin/dev"
root = "crates/agent-tui/src/tui/theme"
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "crates", "synaps-desktop", "src", "palettes.rs")


def git(*a):
    return subprocess.run(["git", "-C", repo, *a], check=True, capture_output=True, text=True).stdout


# Stamped with the last commit that touched the theme directory, not the
# ref's head: an unrelated agent-runtime commit changes nothing here.
commit = git("log", "-1", "--format=%h", "--abbrev=8", ref, "--", root).strip()
head = git("rev-parse", "--short=8", ref).strip()
age = git("log", "-1", "--format=%cr", ref).strip()
mod_rs = git("show", f"{ref}:{root}/mod.rs")

# The Theme struct's colour fields, in declaration order (Option<Color> per-part
# overrides and the ext map are not palette data).
struct = re.search(r"pub\(crate\) struct Theme \{(.*?)\n\}", mod_rs, re.S).group(1)
fields = re.findall(r"pub\(crate\) (\w+): Color,", struct)

# Builtin names, as the TUI's `Theme::builtin` dispatches them.
names = re.findall(r'"([a-z-]+)" => Some\(Self::(\w+)\(\)\)', mod_rs)
names = [(n, f) for n, f in names if n != "myx"]
assert len(names) == 20, len(names)

COLOR = re.compile(r"Color::Rgb\(\s*(\d+),\s*(\d+),\s*(\d+)\s*\)|Color::Reset|\b([A-Z][A-Z_]+)\b")


def color(expr, consts):
    m = COLOR.search(expr)
    if m is None:
        raise ValueError(expr)
    if m.group(1):
        return (int(m.group(1)) << 16) | (int(m.group(2)) << 8) | int(m.group(3))
    if m.group(0) == "Color::Reset":
        return None
    return consts[m.group(4)]


def body(src, fn):
    """`(consts, {field: value})` of `fn name() -> Self { [consts] Self { ... } }`."""
    start = re.search(rf"fn {fn}\(\) -> Self \{{", src).end()
    depth, i = 1, start
    while depth:
        depth += {"{": 1, "}": -1}.get(src[i], 0)
        i += 1
    text = src[start:i - 1]
    consts = {}
    for name, expr in re.findall(r"const (\w+): Color = (Color::Rgb\([^)]*\))", text):
        consts[name] = color(expr, consts)
    inner = text[text.index("Self {") + len("Self {"):]
    inner = re.sub(r"//[^\n]*", "", inner)
    values = {}
    for k, v in re.findall(r"(\w+):\s*(Color::Rgb\([^)]*\)|Color::Reset|[A-Z][A-Z_]+|[^,\n]+)\s*,", inner):
        if k in fields:
            values[k] = color(v, consts)
    return values, "..Self::default()" in inner


default_values, _ = body(mod_rs, "default")
assert set(default_values) == set(fields), set(fields) - set(default_values)
palettes = []
for name, fn in names:
    if fn == "default":
        palettes.append((name, dict(default_values)))
        continue
    src = git("show", f"{ref}:{root}/palettes/{fn}.rs")
    values, spread = body(src, fn)
    full = dict(default_values) if spread else {}
    full.update(values)
    assert set(full) == set(fields), (name, set(fields) - set(full))
    palettes.append((name, full))

# Fields that may be `Color::Reset` (derive) in some palette are `Option<u32>`.
optional = [f for f in fields if any(p[f] is None for _, p in palettes) or default_values[f] is None]


def lit(f, v):
    if f in optional:
        return "None" if v is None else f"Some(0x{v:06x})"
    return f"0x{v:06x}"


lines = [
    f"//! The Synaps TUI's 20 static palettes, as data: every one of the {len(fields)} roles of",
    "//! `agent-tui/src/tui/theme` (`Theme`), `Color::Reset` (derive) as `None`.",
    "//! They are private to agent-tui, so this is a copy. Generated by",
    f"//! `scripts/gen-palettes.py` from agent-runtime {commit} (`{root}`,",
    "//! `mod.rs` and `palettes/*.rs`); `myx` is left out. Do not edit by hand:",
    "//! rerun the script (`--check` says whether it is still in step).",
    "",
    "// A generated table: one line per role. Every role is kept (a theme file",
    "// can set any of them); the desktop reads the ones the spec maps.",
    "#![allow(dead_code, clippy::unreadable_literal)]",
    "",
    f'pub const SOURCE: &str = "agent-runtime {commit}";',
    "",
    "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
    "pub struct Raw {",
]
for f in fields:
    lines.append(f"    pub {f}: {'Option<u32>' if f in optional else 'u32'},")
lines += ["}", "", "/// Every built-in, by the name the TUI's config uses, in its order.", f"pub const THEMES: [(&str, Raw); {len(palettes)}] = ["]
for name, p in palettes:
    lines.append(f'    ("{name}", Raw {{')
    for f in fields:
        lines.append(f"        {f}: {lit(f, p[f])},")
    lines.append("    }),")
lines += [
    "];",
    "",
    "/// Set one role by its TUI name (a `<base>/themes/<name>` file's keys).",
    "/// False for a key that is not a role.",
    "pub fn set(raw: &mut Raw, key: &str, c: u32) -> bool {",
    "    match key {",
]
for f in fields:
    lines.append(f'        "{f}" => raw.{f} = {"Some(c)" if f in optional else "c"},')
lines += ["        _ => return false,", "    }", "    true", "}", ""]
text = "\n".join(lines)

# Formatted as `cargo fmt` leaves it (the workspace's rustfmt.toml), so the
# fmt gate and --check agree.
tmp = out + ".gen.rs"
open(tmp, "w").write(text)
try:
    subprocess.run(["rustfmt", "--edition", "2024", tmp], check=True)
    text = open(tmp).read()
finally:
    os.remove(tmp)


def content(t):
    """The table without its stamp: a newer commit with the same palettes matches."""
    return re.sub(r"agent-runtime [0-9a-f]+", "agent-runtime <commit>", t)


if check:
    have = open(out).read() if os.path.exists(out) else ""
    where = f"agent-runtime {ref} ({head}, {age}; theme dir last changed in {commit}; run `git -C {repo} fetch` for the latest)"
    if content(have) != content(text):
        print(f"palettes.rs differs from {where}: rerun scripts/gen-palettes.py")
        sys.exit(1)
    print(f"palettes.rs matches {where}")
else:
    open(out, "w").write(text)
    print(f"wrote {os.path.normpath(out)} from agent-runtime {commit}: {len(palettes)} palettes, {len(fields)} roles")
